package phase_02_variables_data_types.operators;

public class arithmetic {
    public static void main(String[] args) {
        int a = 20;
        int b = 6;

        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
    }
}
